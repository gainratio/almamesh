import { readFileSync } from 'node:fs';
import path from 'node:path';

import { describe, it, expect } from 'vitest';

import {
  PUBLIC_ROUTE_HEADS,
  PUBLIC_ROUTE_PATHS,
  PRIVATE_ROUTE_PREFIXES,
  PRERENDER_OUTPUT_FILES,
  SITE_ORIGIN,
  OG_IMAGE_URL,
  getRouteHead,
  headElementsFor,
  ogImageUrlFor,
  ogSlugFor,
  prerenderOutputFile,
} from './routeHead';

/** Flatten the plugin-shaped elements into an easy lookup for assertions. */
function metaByName(els: ReadonlyArray<{ type: string; props: Record<string, string> }>) {
  const out = new Map<string, Record<string, string>>();
  for (const el of els) {
    const key =
      el.type === 'link'
        ? `link:${el.props.rel}`
        : `${el.type}:${el.props.name ?? el.props.property ?? ''}`;
    out.set(key, el.props);
  }
  return out;
}

describe('routeHead — the single per-route SEO source', () => {
  it('covers exactly the five public routes', () => {
    expect([...PUBLIC_ROUTE_PATHS].sort()).toEqual(
      ['/', '/welcome', '/privacy', '/terms', '/data-deletion'].sort(),
    );
    expect(PUBLIC_ROUTE_HEADS).toHaveLength(5);
  });

  it('gives every route a unique title, description, and canonical', () => {
    const titles = PUBLIC_ROUTE_HEADS.map((h) => h.title);
    const descriptions = PUBLIC_ROUTE_HEADS.map((h) => h.description);
    const canonicals = PUBLIC_ROUTE_HEADS.map((h) => h.canonical);
    expect(new Set(titles).size).toBe(titles.length);
    expect(new Set(descriptions).size).toBe(descriptions.length);
    expect(new Set(canonicals).size).toBe(canonicals.length);
  });

  it('canonical is the absolute almamesh.com URL of the route (no trailing slash except /)', () => {
    for (const head of PUBLIC_ROUTE_HEADS) {
      const expected = head.path === '/' ? `${SITE_ORIGIN}/` : `${SITE_ORIGIN}${head.path}`;
      expect(head.canonical).toBe(expected);
      expect(head.canonical.startsWith('https://almamesh.com')).toBe(true);
    }
  });

  it('titles and descriptions are search-result sized', () => {
    for (const head of PUBLIC_ROUTE_HEADS) {
      expect(head.title.length).toBeGreaterThanOrEqual(15);
      expect(head.title.length).toBeLessThanOrEqual(70);
      expect(head.description.length).toBeGreaterThanOrEqual(50);
      expect(head.description.length).toBeLessThanOrEqual(160);
    }
  });

  it('privacy description does not claim the birth date never leaves', () => {
    // With AI on, planet positions leave the device and can reveal the birth date.
    const description = getRouteHead('/privacy')!.description.toLowerCase();
    expect(description).not.toContain('never leave');
    expect(description).toContain('can reveal your birth date');
  });

  it('headElementsFor emits description + canonical + OG + twitter for a route', () => {
    const head = getRouteHead('/welcome');
    expect(head).toBeDefined();
    const els = metaByName(headElementsFor('/welcome'));

    expect(els.get('meta:description')?.content).toBe(head!.description);
    expect(els.get('link:canonical')?.href).toBe(head!.canonical);
    expect(els.get('meta:og:title')?.content).toBe(head!.title);
    expect(els.get('meta:og:description')?.content).toBe(head!.description);
    expect(els.get('meta:og:url')?.content).toBe(head!.canonical);
    expect(els.get('meta:og:image')?.content).toBe(`${SITE_ORIGIN}/og/welcome.png`);
    expect(els.get('meta:og:type')?.content).toBe('website');
    expect(els.get('meta:og:site_name')?.content).toBe('AlmaMesh');
    expect(els.get('meta:twitter:card')?.content).toBe('summary_large_image');
    expect(els.get('meta:twitter:title')?.content).toBe(head!.title);
    expect(els.get('meta:twitter:image')?.content).toBe(`${SITE_ORIGIN}/og/welcome.png`);
  });

  it('every public route produces the same SHAPE of head elements', () => {
    const shapes = PUBLIC_ROUTE_PATHS.map((p) =>
      headElementsFor(p)
        .map((el) => `${el.type}:${el.props.rel ?? el.props.name ?? el.props.property}`)
        .sort()
        .join('|'),
    );
    expect(new Set(shapes).size).toBe(1);
  });

  it('returns undefined for private routes', () => {
    expect(getRouteHead('/dashboard')).toBeUndefined();
    expect(getRouteHead('/settings/profile')).toBeUndefined();
  });

  it('the private prefixes cover the whole app surface (robots.txt parity)', () => {
    expect([...PRIVATE_ROUTE_PREFIXES].sort()).toEqual(
      [
        '/dashboard',
        '/onboarding',
        '/predictive',
        '/report',
        '/mesh',
        '/rectify',
        '/settings',
        '/life',
      ].sort(),
    );
  });
});

describe('per-route OG cards — /og/<slug>.png generated by scripts/generate-og-images.mjs', () => {
  it('maps the root to the "home" slug and every other route to its path slug', () => {
    expect(ogSlugFor('/')).toBe('home');
    expect(ogSlugFor('/welcome')).toBe('welcome');
    expect(ogSlugFor('/privacy')).toBe('privacy');
    expect(ogSlugFor('/terms')).toBe('terms');
    expect(ogSlugFor('/data-deletion')).toBe('data-deletion');
  });

  it('gives every public route its own absolute og image URL', () => {
    const urls = PUBLIC_ROUTE_PATHS.map((p) => ogImageUrlFor(p));
    expect(new Set(urls).size).toBe(urls.length);
    for (const [i, path] of PUBLIC_ROUTE_PATHS.entries()) {
      expect(urls[i]).toBe(`${SITE_ORIGIN}/og/${ogSlugFor(path)}.png`);
    }
  });

  it('falls back to the shared brand card for anything unlisted', () => {
    expect(ogImageUrlFor('/dashboard')).toBe(OG_IMAGE_URL);
    expect(ogImageUrlFor('/nope')).toBe(OG_IMAGE_URL);
  });

  it('headElementsFor carries the per-route image with correct 1200x630 dimensions', () => {
    for (const path of PUBLIC_ROUTE_PATHS) {
      const els = metaByName(headElementsFor(path));
      expect(els.get('meta:og:image')?.content).toBe(ogImageUrlFor(path));
      expect(els.get('meta:twitter:image')?.content).toBe(ogImageUrlFor(path));
      expect(els.get('meta:og:image:width')?.content).toBe('1200');
      expect(els.get('meta:og:image:height')?.content).toBe('630');
    }
  });

  it('every referenced card EXISTS in public/og as a 1200x630 PNG under 200 KB', () => {
    // Locks the wiring to the committed generator output: a route pointing at a
    // card that is not on disk would ship a broken share preview.
    for (const route of PUBLIC_ROUTE_PATHS) {
      // Vitest runs from the apps/web package root.
      const file = path.join(process.cwd(), 'public', 'og', `${ogSlugFor(route)}.png`);
      const bytes = readFileSync(file);
      // PNG signature + IHDR width/height (big-endian at offsets 16/20).
      expect(bytes.subarray(0, 8)).toEqual(
        Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
      );
      expect(bytes.readUInt32BE(16)).toBe(1200);
      expect(bytes.readUInt32BE(20)).toBe(630);
      expect(bytes.byteLength).toBeLessThan(200 * 1024);
    }
  });
});

describe('prerenderOutputFile — FLAT dist layout for the no-slash canonical', () => {
  it('maps the root to index.html', () => {
    expect(prerenderOutputFile('/')).toBe('index.html');
  });

  it('maps each non-root public route to a FLAT <slug>.html (never a nested index.html)', () => {
    expect(prerenderOutputFile('/welcome')).toBe('welcome.html');
    expect(prerenderOutputFile('/privacy')).toBe('privacy.html');
    expect(prerenderOutputFile('/terms')).toBe('terms.html');
    expect(prerenderOutputFile('/data-deletion')).toBe('data-deletion.html');
  });

  it('emits one relative, slash-free flat file per public route (root aside)', () => {
    expect(PRERENDER_OUTPUT_FILES).toHaveLength(PUBLIC_ROUTE_PATHS.length);
    for (const file of PRERENDER_OUTPUT_FILES) {
      expect(file.startsWith('/')).toBe(false);
      expect(file.endsWith('.html')).toBe(true);
      // No nested directory index — a slash would 308 the no-slash canonical away.
      if (file !== 'index.html') expect(file.includes('/')).toBe(false);
    }
    // The flat file's basename (minus .html) is the route slug -> CF serves it
    // at the exact no-slash canonical path (og:url + sitemap + canonical tag).
    for (const head of PUBLIC_ROUTE_HEADS) {
      if (head.path === '/') continue;
      expect(prerenderOutputFile(head.path)).toBe(`${head.path.replace(/^\//, '')}.html`);
    }
  });
});
